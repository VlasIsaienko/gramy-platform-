-- ============================================================
-- Миграция: group_number в teams — состав группы должен быть
-- виден независимо от того, сгенерированы ли уже матчи для неё
-- (например, после ручного переноса участника группа может
-- временно остаться с 1 человеком и без единого матча).
-- ============================================================
-- Как применить: Supabase → твой проект → SQL Editor →
-- вставить этот файл целиком → Run.
-- ============================================================

alter table teams add column group_number integer;

-- Бэкфилл для уже сгенерированных сеток формата Groups: берём
-- group_number из существующих matches, если он там уже есть.
update teams t
set group_number = m.group_number
from matches m
where (t.id = m.team_a_id or t.id = m.team_b_id)
  and m.group_number is not null
  and t.group_number is null;
