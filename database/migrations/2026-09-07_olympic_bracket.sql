-- Позиция матча внутри раунда — нужна, чтобы понимать, чьи победители
-- встретятся в следующем раунде (позиции 0+1 -> позиция 0 следующего
-- раунда, 2+3 -> позиция 1, и т.д.). null для round_robin/groups.
alter table matches add column bracket_position integer;

-- Отдельно помечает матч за 3-е место (проигравшие полуфиналов) —
-- он не часть основной сетки на выбывание.
alter table matches add column match_type text not null default 'standard'
  check (match_type in ('standard','third_place'));

-- Решение администратора при генерации сетки Olympic: играть ли матч
-- за 3-е место. Нужно хранить на категории, а не только в UI, — оно
-- понадобится позже, когда полуфиналы будут сыграны и нужно решить,
-- генерировать ли этот матч вместе с финалом.
alter table categories add column third_place_match boolean not null default true;
