-- ============================================================
-- Миграция: запретить турниры с датой в прошлом на уровне БД
-- ============================================================
-- Как применить: Supabase → твой проект → SQL Editor →
-- вставить этот файл целиком → Run.
--
-- NOT VALID: не проверяет существующие строки (в тестовых данных
-- есть турниры с датой в прошлом), но constraint сразу начинает
-- действовать для всех новых INSERT и UPDATE.
-- ============================================================

alter table tournaments
  add constraint tournaments_date_not_past check (date >= current_date) not valid;
